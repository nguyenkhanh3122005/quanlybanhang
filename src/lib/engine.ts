async function probeNonStreaming(
  baseUrl: string,
  headers: Record<string, string>,
  model: string,
  startTime: number
): Promise<ProbeResult> {
  const res = await fetch(`${baseUrl}/v1/messages`, {
    method: "POST",
    headers,
    body: JSON.stringify({
      model,
      max_tokens: 30,
      messages: [{ role: "user", content: "Reply with the exact word 'PONG'." }],
    }),
  });

  const latencyMs = Date.now() - startTime;
  if (!res.ok) {
    const errorText = await res.text();
    return {
      id: "non_streaming",
      nameVi: "Cấu trúc phi luồng",
      status: "failed",
      score: 0,
      latencyMs,
      error: `HTTP ${res.status}: ${errorText.slice(0, 150)}`,
    };
  }

  const json = await res.json();
  const isValidSchema =
    json &&
    typeof json.id === "string" &&
    json.type === "message" &&
    json.role === "assistant" &&
    Array.isArray(json.content) &&
    json.usage &&
    typeof json.usage.input_tokens === "number";

  return {
    id: "non_streaming",
    nameVi: "Cấu trúc phi luồng",
    status: isValidSchema ? "passed" : "failed",
    score: isValidSchema ? 100 : 20,
    latencyMs,
    details: isValidSchema
      ? "JSON response v1/messages đạt chuẩn Anthropic (id, type: 'message', content array, usage)."
      : "Phản hồi JSON không đúng chuẩn schema Anthropic Messages API v1.",
    rawResponse: json,
  };
}

async function probeStreaming(
  baseUrl: string,
  headers: Record<string, string>,
  model: string,
  startTime: number
): Promise<ProbeResult> {
  const res = await fetch(`${baseUrl}/v1/messages`, {
    method: "POST",
    headers,
    body: JSON.stringify({
      model,
      max_tokens: 50,
      stream: true,
      messages: [{ role: "user", content: "Count from 1 to 5." }],
    }),
  });

  const latencyMs = Date.now() - startTime;
  if (!res.ok) {
    const errorText = await res.text();
    return {
      id: "streaming",
      nameVi: "Cấu trúc luồng",
      status: "failed",
      score: 0,
      latencyMs,
      error: `HTTP ${res.status}: ${errorText.slice(0, 150)}`,
    };
  }

  const text = await res.text();
  const hasMessageStart = text.includes("event: message_start");
  const hasContentDelta = text.includes("content_block_delta");
  const hasMessageStop = text.includes("event: message_stop");

  const passed = hasMessageStart && hasContentDelta && hasMessageStop;

  return {
    id: "streaming",
    nameVi: "Cấu trúc luồng",
    status: passed ? "passed" : "failed",
    score: passed ? 100 : 30,
    latencyMs,
    details: passed
      ? `SSE stream chuẩn với đầy đủ message_start, content_block_delta và message_stop (TTFT: ${latencyMs}ms).`
      : "Thiếu các event SSE chuẩn của Anthropic hoặc proxy truyền tải dạng buffer giả lập.",
  };
}

async function probeToolUse(
  baseUrl: string,
  headers: Record<string, string>,
  model: string,
  startTime: number
): Promise<ProbeResult> {
  const res = await fetch(`${baseUrl}/v1/messages`, {
    method: "POST",
    headers,
    body: JSON.stringify({
      model,
      max_tokens: 100,
      tools: [
        {
          name: "get_current_weather",
          description: "Get the current weather for a city.",
          input_schema: {
            type: "object",
            properties: {
              city: { type: "string" },
            },
            required: ["city"],
          },
        },
      ],
      messages: [{ role: "user", content: "What is the weather in Tokyo?" }],
    }),
  });

  const latencyMs = Date.now() - startTime;
  if (!res.ok) {
    return {
      id: "tool_use",
      nameVi: "Sử dụng dụng cụ",
      status: "failed",
      score: 0,
      latencyMs,
      error: `Proxy từ chối hỗ trợ tools: HTTP ${res.status}`,
    };
  }

  const json = await res.json();
  const hasToolUse =
    json?.stop_reason === "tool_use" ||
    (Array.isArray(json?.content) &&
      json.content.some((c: any) => c.type === "tool_use" && c.name === "get_current_weather"));

  return {
    id: "tool_use",
    nameVi: "Sử dụng dụng cụ",
    status: hasToolUse ? "passed" : "failed",
    score: hasToolUse ? 100 : 10,
    latencyMs,
    details: hasToolUse
      ? "Hỗ trợ chuẩn native tool_use. Function calling trả về schema JSON input chính xác."
      : "Proxy không kích hoạt tool_use block hoặc trả lời dạng text thường.",
    rawResponse: json,
  };
}

