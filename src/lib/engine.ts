async function probeTokenAudit(
  baseUrl: string,
  headers: Record<string, string>,
  model: string,
  startTime: number
): Promise<ProbeResult> {
  const testPrompt = "Calculate 15 * 8 and explain in one sentence.";
  const res = await fetch(`${baseUrl}/v1/messages`, {
    method: "POST",
    headers,
    body: JSON.stringify({
      model,
      max_tokens: 30,
      messages: [{ role: "user", content: testPrompt }],
    }),
  });

  const latencyMs = Date.now() - startTime;
  if (!res.ok) {
    return {
      id: "token_audit",
      nameVi: "Kiểm toán sử dụng token",
      status: "failed",
      score: 0,
      latencyMs,
      error: `HTTP ${res.status}`,
    };
  }

  const json = await res.json();
  const inputTokens = json?.usage?.input_tokens || 0;
  // Standard input tokens for this prompt is around 18-22
  const isSuspicious = inputTokens > 45 || inputTokens < 5;

  return {
    id: "token_audit",
    nameVi: "Kiểm toán sử dụng token",
    status: isSuspicious ? "failed" : "passed",
    score: isSuspicious ? 40 : 100,
    latencyMs,
    details: isSuspicious
      ? `Phát hiện số token input bất thường (${inputTokens} tokens cho prompt ngắn 1 câu). Nghi vấn độn token.`
      : `Số token báo cáo (${inputTokens} input) khớp chuẩn xác với dung lượng prompt thực tế. Không bị độn cước.`,
  };
}

